// Regenerates CONTRIBUTORS.md from the files in contributors/.
// Runs on every push to main. Writes nothing if the output has not changed.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { validateContributor, SKILLS, YEARS } from "./lib/contributor.mjs";

const DIR = "contributors";
const OUT = "CONTRIBUTORS.md";

function load() {
  const people = [];
  const skipped = [];

  for (const entry of readdirSync(DIR).sort()) {
    if (!entry.endsWith(".md") || entry === "TEMPLATE.md") continue;
    const expected = entry.replace(/\.md$/, "");
    const result = validateContributor(readFileSync(join(DIR, entry), "utf8"), expected);
    if (result.ok) people.push(result.contributor);
    else skipped.push({ entry, problems: result.problems });
  }

  return { people, skipped };
}

function render(people) {
  const byYear = YEARS.map((year) => [year, people.filter((p) => p.year === year).length]).filter(([, n]) => n > 0);

  const skillCounts = SKILLS.map((skill) => [skill, people.filter((p) => p.knows.includes(skill)).length])
    .filter(([, n]) => n > 0)
    .sort((a, b) => b[1] - a[1]);

  const rows = [...people]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map(
      (p) =>
        `| [${p.name}](https://github.com/${p.github}) | ${p.year} | ${p.branch} | ${p.knows.join(", ")} | ${p.wants || "—"} |`,
    );

  const lines = [
    "<!-- Generated by scripts/build-contributors.mjs. Edit contributors/<your-username>.md instead. -->",
    "",
    "# Contributors",
    "",
    `${people.length} ${people.length === 1 ? "person has" : "people have"} made their first contribution to VOSS Labs.`,
    "",
  ];

  if (byYear.length) lines.push(`**By year:** ${byYear.map(([y, n]) => `${y} ${n}`).join(" · ")}`, "");
  if (skillCounts.length) lines.push(`**By skill:** ${skillCounts.map(([s, n]) => `${s} ${n}`).join(" · ")}`, "");

  if (rows.length) {
    lines.push("| Name | Year | Branch | Knows | Wants to learn |", "| --- | --- | --- | --- | --- |", ...rows, "");
  }

  lines.push("---", "", "Not on this list yet? [Start here.](README.md)", "");

  return lines.join("\n");
}

const { people, skipped } = load();

for (const { entry, problems } of skipped) {
  console.warn(`Skipped ${DIR}/${entry}: ${problems.map((p) => p.title).join(" ")}`);
}

const next = render(people);
const current = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return "";
  }
})();

if (next === current) {
  console.log("CONTRIBUTORS.md is already up to date.");
} else {
  writeFileSync(OUT, next);
  console.log(`Wrote ${OUT} with ${people.length} contributor(s).`);
}
